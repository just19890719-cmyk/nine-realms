-- 道具的上架、購買、下架、領取都由伺服器直接改雲端存檔（遊戲端做完會重新讀檔），所以 save_game 不用改。
-- 1) market 多 kind（'w' 武器／'i' 道具）、item、grp（items 或 mats）、qty、left_qty 欄位
-- 2) market_fill：道具每一筆成交（買了幾個、總價、賣家領取了沒）
-- 3) 新函式 market_list_item／market_buy_item／market_cancel_item／market_item_pending／market_item_claim
-- 4) 舊的 market_buy／market_cancel／market_pending 只處理武器

alter table public.market add column if not exists kind text not null default 'w';
alter table public.market add column if not exists item text;
alter table public.market add column if not exists grp text;
alter table public.market add column if not exists qty integer;
alter table public.market add column if not exists left_qty integer;

create table if not exists public.market_fill (
  id bigint generated by default as identity primary key,
  listing bigint not null references public.market(id),
  seller uuid not null,
  buyer uuid not null,
  item text not null,
  qty integer not null,
  cur text not null,
  total bigint not null,
  created_at timestamptz not null default now(),
  settled boolean not null default false);
create index if not exists market_fill_seller_idx on public.market_fill (seller, settled);
alter table public.market_fill enable row level security;   -- 沒有開放直接讀寫，只能透過下面的函式

-- 存檔裡某個道具／材料的數量加減（p_n 可以是負的）
create or replace function public.mk_item_add(p_uid uuid, p_grp text, p_k text, p_n bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  update saves set data = jsonb_set(data, array[p_grp, p_k], to_jsonb(greatest(0, coalesce((data->p_grp->>p_k)::bigint, 0) + p_n)), true)
    where user_id = p_uid;
end $$;
create or replace function public.mk_cur_add(p_uid uuid, p_cur text, p_n bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  update saves set data = jsonb_set(data, array[p_cur], to_jsonb(greatest(0, coalesce((data->>p_cur)::float8, 0) + p_n)), true)
    where user_id = p_uid;
end $$;

-- 上架道具：數量要夠，上架時直接從雲端存檔扣掉
create or replace function public.market_list_item(p_item text, p_qty int, p_cur text, p_price bigint, p_nick text, p_sid text)
returns bigint language plpgsql security definer set search_path = public as $$
declare sv jsonb; g text; have bigint; n int; new_id bigint;
begin
  perform mk_check(p_sid);
  if p_cur not in ('gold','gems') or p_price < 10
     or (p_cur = 'gold' and p_price > 99999999) or (p_cur = 'gems' and p_price > 999999) then raise exception 'bad price'; end if;
  if p_qty is null or p_qty < 1 or p_qty > 999999 or p_item !~ '^[a-z0-9_]{1,24}$' then raise exception 'bad qty'; end if;
  select data into sv from saves where user_id = auth.uid() for update;
  g := case when sv->'items' ? p_item then 'items' when sv->'mats' ? p_item then 'mats' end;
  if g is null then raise exception 'not owned'; end if;
  have := coalesce((sv->g->>p_item)::bigint, 0);
  if have < p_qty then raise exception 'not enough items'; end if;
  select count(*) into n from market where seller = auth.uid() and status = 'open' and expires_at > now();
  if n >= 10 then raise exception 'listing limit'; end if;
  perform mk_item_add(auth.uid(), g, p_item, -p_qty);
  insert into market (seller, seller_nick, weapon, bp, lv, q, cur, price, kind, item, grp, qty, left_qty)
    values (auth.uid(), left(p_nick, 16), jsonb_build_object('item', p_item), null, 0, 0, p_cur, p_price, 'i', p_item, g, p_qty, p_qty)
    returning id into new_id;
  return new_id;
end $$;

-- 買道具：可以只買一部分；錢夠才成交，直接從買家存檔扣錢、加道具
create or replace function public.market_buy_item(p_id bigint, p_qty int, p_sid text)
returns public.market_fill language plpgsql security definer set search_path = public as $$
declare r market; f market_fill; bal float8; tot bigint;
begin
  perform mk_check(p_sid);
  select * into r from market where id = p_id and kind = 'i' and status = 'open' and expires_at > now() and seller <> auth.uid() for update;
  if not found then raise exception 'not available'; end if;
  if p_qty is null or p_qty < 1 or p_qty > r.left_qty then raise exception 'bad qty'; end if;
  tot := r.price * p_qty;
  select coalesce((data->>r.cur)::float8, 0) into bal from saves where user_id = auth.uid() for update;
  if coalesce(bal, 0) < tot then raise exception 'not enough'; end if;
  perform mk_cur_add(auth.uid(), r.cur, -tot);
  perform mk_item_add(auth.uid(), r.grp, r.item, p_qty);
  update market set left_qty = left_qty - p_qty, buyer = auth.uid(), buyer_ack = true,
      status = case when left_qty - p_qty <= 0 then 'sold' else status end,
      sold_at = case when left_qty - p_qty <= 0 then now() else sold_at end
    where id = r.id;
  insert into market_fill (listing, seller, buyer, item, qty, cur, total) values (r.id, r.seller, auth.uid(), r.item, p_qty, r.cur, tot)
    returning * into f;
  return f;
end $$;

-- 下架道具：剩下的數量直接退回賣家存檔
create or replace function public.market_cancel_item(p_id bigint, p_sid text)
returns public.market language plpgsql security definer set search_path = public as $$
declare r market;
begin
  perform mk_check(p_sid);
  select * into r from market where id = p_id and kind = 'i' and seller = auth.uid() and status = 'open' for update;
  if not found then raise exception 'not available'; end if;
  perform mk_item_add(auth.uid(), r.grp, r.item, r.left_qty);
  update market set status = 'cancelled', settled = true, left_qty = 0 where id = r.id returning * into r;
  return r;
end $$;

-- 待領取的道具：賣出的錢（每筆成交）、到期沒賣完要退回的數量
create or replace function public.market_item_pending(p_sid text)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform mk_check(p_sid);
  update market set status = 'expired' where seller = auth.uid() and status = 'open' and expires_at <= now();
  return coalesce((select jsonb_agg(x) from (
      select 'f' || f.id as key, 'sold' as status, f.item, f.qty, f.cur, f.total, floor(f.total * 0.95)::bigint as net
        from market_fill f where f.seller = auth.uid() and f.settled = false
      union all
      select 'b' || m.id, 'expired', m.item, m.left_qty, m.cur, 0, 0
        from market m where m.seller = auth.uid() and m.kind = 'i' and m.status = 'expired' and m.settled = false and m.left_qty > 0) x), '[]'::jsonb);
end $$;

-- 全部領取（道具部分）：錢、退回的道具直接加進雲端存檔
create or replace function public.market_item_claim(p_sid text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare f market_fill; m market; g float8 := 0; gm float8 := 0; back int := 0;
begin
  perform mk_check(p_sid);
  perform 1 from saves where user_id = auth.uid() for update;
  update market set status = 'expired' where seller = auth.uid() and status = 'open' and expires_at <= now();
  for f in select * from market_fill where seller = auth.uid() and settled = false for update loop
    perform mk_cur_add(auth.uid(), f.cur, floor(f.total * 0.95)::bigint);
    if f.cur = 'gems' then gm := gm + floor(f.total * 0.95); else g := g + floor(f.total * 0.95); end if;
    update market_fill set settled = true where id = f.id;
  end loop;
  for m in select * from market where seller = auth.uid() and kind = 'i' and status in ('expired', 'sold') and settled = false for update loop
    if m.status = 'expired' and m.left_qty > 0 then perform mk_item_add(auth.uid(), m.grp, m.item, m.left_qty); back := back + m.left_qty; end if;
    update market set settled = true, left_qty = 0 where id = m.id;
  end loop;
  return jsonb_build_object('gold', g, 'gems', gm, 'back', back);
end $$;

-- 舊函式只處理武器（避免把道具當成武器整批賣掉）
create or replace function public.market_buy(p_id bigint, p_sid text)
returns public.market language plpgsql security definer set search_path = public as $$
declare r market; bal float8;
begin
  perform mk_check(p_sid);
  select * into r from market where id = p_id and kind = 'w' and status = 'open' and expires_at > now() and seller <> auth.uid() for update;
  if not found then raise exception 'not available'; end if;
  select coalesce((data->>r.cur)::float8, 0) into bal from saves where user_id = auth.uid();
  if coalesce(bal, 0) < r.price then raise exception 'not enough'; end if;
  update saves set data = data || jsonb_build_object(r.cur, bal - r.price,
      'mk', coalesce(data->'mk', '{}'::jsonb) || jsonb_build_object('paid', coalesce(data->'mk'->'paid', '[]'::jsonb) || to_jsonb(r.id)))
    where user_id = auth.uid();
  update market set status = 'sold', buyer = auth.uid(), sold_at = now() where id = r.id returning * into r;
  return r;
end $$;

create or replace function public.market_cancel(p_id bigint, p_sid text)
returns public.market language plpgsql security definer set search_path = public as $$
declare r market;
begin
  perform mk_check(p_sid);
  update market set status = 'cancelled' where id = p_id and kind = 'w' and seller = auth.uid() and status = 'open' returning * into r;
  if not found then raise exception 'not available'; end if;
  return r;
end $$;

create or replace function public.market_pending(p_sid text)
returns setof public.market language plpgsql security definer set search_path = public as $$
begin
  perform mk_check(p_sid);
  update market set status = 'expired' where seller = auth.uid() and status = 'open' and expires_at <= now();
  return query select * from market
    where kind = 'w' and ((seller = auth.uid() and settled = false and status in ('sold','expired','cancelled'))
       or (buyer = auth.uid() and buyer_ack = false));
end $$;

