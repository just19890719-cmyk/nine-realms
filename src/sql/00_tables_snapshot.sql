-- ===== 九界鐵匠 資料表備份（2026-10-22 從正式資料庫匯出整理） =====
-- 只有重建一個全新的 Supabase 專案時才需要執行（正式資料庫已經有了，不要重跑）。
-- 執行順序：00 → 01 → 02 → 03 → 04。
-- 注意：匯出結果沒有包含 NOT NULL、外鍵、identity 等細節，這裡依程式用法補上，可能與正式資料庫略有不同。

-- 雲端存檔（每個帳號一筆；只能透過 create_save / claim_session / save_game 寫入）
create table if not exists public.saves (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nickname text,
  data jsonb,
  updated_at timestamptz not null default now(),
  session_id text);
alter table public.saves enable row level security;
drop policy if exists "read own save" on public.saves;
create policy "read own save" on public.saves for select using (auth.uid() = user_id);

-- 排行榜（每位玩家每座村莊一筆最佳紀錄；只能透過 lb_submit / lb_rename 寫入）
create table if not exists public.lb (
  user_id uuid not null references auth.users(id) on delete cascade,
  village integer not null,
  nick text,
  p integer not null,
  w jsonb,
  updated_at timestamptz not null default now(),
  primary key (user_id, village));
alter table public.lb enable row level security;
drop policy if exists "lb read" on public.lb;
create policy "lb read" on public.lb for select using (true);

-- 交易所（只能透過 market_* 函式寫入）
create table if not exists public.market (
  id bigint generated by default as identity primary key,
  seller uuid not null,
  seller_nick text,
  weapon jsonb not null,
  bp text,
  lv integer default 0,
  q integer default 0,
  cur text not null,
  price bigint not null,
  status text not null default 'open',
  buyer uuid,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '3 days'),
  sold_at timestamptz,
  settled boolean not null default false,
  buyer_ack boolean not null default false);
create index if not exists market_open_idx on public.market (status, expires_at);
create index if not exists market_seller_idx on public.market (seller, status);
alter table public.market enable row level security;
drop policy if exists "market read" on public.market;
create policy "market read" on public.market for select
  using (status = 'open' or seller = auth.uid() or buyer = auth.uid());

-- 排行榜改暱稱（lb_submit 在 04 檔案）
create or replace function public.lb_rename(p_nick text) returns void
language plpgsql security definer set search_path = public as $$
begin
  update lb set nick = left(p_nick, 16) where user_id = auth.uid();
end $$;

